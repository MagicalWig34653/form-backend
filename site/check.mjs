// Dependency-free checks of site/dist: every internal link and anchor resolves, every page has one h1, title and description,
// no external resources are loaded (everything except explicit <a href> links stays on the same origin).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = path.join(path.dirname(fileURLToPath(import.meta.url)), 'dist');
const pages = fs.readdirSync(dist).filter((f) => f.endsWith('.html') && f !== '404.html');
const ids = {};
const html = {};
for (const p of pages) {
  html[p] = fs.readFileSync(path.join(dist, p), 'utf8');
  ids[p] = new Set([...html[p].matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]));
}
let bad = 0;
const fail = (m) => { console.error('FAIL', m); bad++; };
for (const p of pages) {
  const h = html[p];
  if ((h.match(/<h1[\s>]/g) || []).length !== 1) fail(`${p}: needs exactly one h1`);
  if (!/<title>[^<]+<\/title>/.test(h) || !/<meta name="description" content="[^"]+"/.test(h)) fail(`${p}: title/description`);
  for (const m of h.matchAll(/(?:src|href)="([^"]+)"/g)) {
    const u = m[1];
    if (/^(https?:|mailto:)/.test(u)) { if (/<(?:script|link|img)[^>]+(?:src|href)="/.test(h) && new RegExp(`<(?:script|img)[^>]+src="${u.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`).test(h)) fail(`${p}: external resource ${u}`); continue; }
    const [file, frag] = u.split('#');
    const target = file === '' ? p : file === './' ? 'index.html' : file.replace(/^\.\//, '');
    if (!fs.existsSync(path.join(dist, target))) { fail(`${p}: missing target ${u}`); continue; }
    if (frag && target.endsWith('.html')) {
      // anchors generated by site.js (h2/h3 slugs) are validated against the heading text
      const slug = (t) => t.toLowerCase().replace(/ä/g, 'ae').replace(/ö/g, 'oe').replace(/ü/g, 'ue').replace(/ß/g, 'ss').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      const heads = [...(html[target] || '').matchAll(/<h[23][^>]*>(.*?)<\/h[23]>/gs)].map((x) => slug(x[1].replace(/<[^>]+>/g, '')));
      if (!ids[target]?.has(frag) && !heads.includes(frag)) fail(`${p}: missing anchor ${u}`);
    }
  }
}
console.log(bad ? `${bad} problem(s)` : `ok: ${pages.length} pages, links and anchors resolve`);
process.exit(bad ? 1 : 0);
